def _float(value: Tensor | float) -> float:
    if isinstance(value, Tensor):
        return float(value.detach())
    return float(value)


def _rmse(left: Tensor, right: Tensor) -> float:
    return _float((left.detach() - right.detach()).square().mean().sqrt())


class MonotoneBranchNetwork(nn.Module):
    """Piecewise-linear neural lattice with a certified slope bound."""

    def __init__(self, width: int = 12, maximum_slope: float = 1.5) -> None:
        super().__init__()
        if width < 2 or maximum_slope <= 0.0:
            raise ValueError("invalid monotone branch configuration")
        self.maximum_slope = float(maximum_slope)
        self.register_buffer("knots", torch.linspace(-1.0, 1.0, width))
        spacing = 2.0 / (width - 1)
        self.register_buffer(
            "maximum_drop", torch.tensor(maximum_slope * spacing)
        )
        self.raw_decrements = nn.Parameter(
            torch.full((width - 1,), -0.4054651081081643)
        )
        self.anchor = nn.Parameter(torch.tensor(0.0))

    @property
    def slope_bound(self) -> Tensor:
        return self.maximum_drop / (self.knots[1] - self.knots[0])

    def forward(self, coordinate: Tensor) -> Tensor:
        decrements = self.maximum_drop * torch.sigmoid(
            self.raw_decrements
        )
        values = torch.cat(
            [
                self.anchor[None],
                self.anchor - torch.cumsum(decrements, dim=0),
            ]
        )
        scaled = (
            (coordinate.clamp(-1.0, 1.0) + 1.0)
            * (self.knots.numel() - 1)
            / 2.0
        )
        index = torch.floor(scaled).to(torch.long).clamp(
            0, self.knots.numel() - 2
        )
        fraction = scaled - index
        return values[index] + fraction * (
            values[index + 1] - values[index]
        )


class CertifiedNeuralKappaController(nn.Module):
    """Two monotone neural branches with the controller-compatible API."""

    negative_interval = BroadBasinKappaController.negative_interval
    positive_interval = BroadBasinKappaController.positive_interval

    def __init__(self, width: int = 24) -> None:
        super().__init__()
        self.negative = MonotoneBranchNetwork(width)
        self.positive = MonotoneBranchNetwork(width)

    @staticmethod
    def _coordinate(
        value: Tensor, interval: tuple[float, float]
    ) -> Tensor:
        lower, upper = interval
        return (2.0 * (value - lower) / (upper - lower) - 1.0).clamp(
            -1.0, 1.0
        )

    def residual(self, z: Tensor) -> Tensor:
        negative = self.negative(self._coordinate(z, self.negative_interval))
        positive = self.positive(self._coordinate(z, self.positive_interval))
        return torch.where(z < 0.0, negative, positive)

    def forward(self, z: Tensor, base_kappa: Tensor) -> Tensor:
        return base_kappa + self.residual(z)


class ConvexDissipationPotential(nn.Module):
    """Smooth convex potential with exact D(0)=0 and grad D(0)=0."""

    def __init__(self, width: int = 8) -> None:
        super().__init__()
        self.raw_diagonal = nn.Parameter(torch.zeros(2))
        angles = torch.linspace(0.0, math.pi, width + 1)[:-1]
        directions = torch.stack([torch.cos(angles), torch.sin(angles)], -1)
        self.directions = nn.Parameter(directions)
        self.raw_weights = nn.Parameter(torch.full((width,), -3.0))

    def forward(self, force: Tensor) -> Tensor:
        diagonal = F.softplus(self.raw_diagonal) + 1.0e-6
        quadratic = 0.5 * (diagonal * force.square()).sum(dim=-1)
        projection = force @ self.directions.T
        even_softplus = (
            F.softplus(projection)
            + F.softplus(-projection)
            - 2.0 * math.log(2.0)
        )
        return quadratic + torch.einsum(
            "bi,i->b", even_softplus, F.softplus(self.raw_weights)
        )


class NeuralDissipationTheory33(Theory33HybridTesseract):
    """Theory33 whose scalar relaxation is generated by a convex potential."""

    def __init__(
        self, dissipation: ConvexDissipationPotential, **kwargs: Any
    ) -> None:
        super().__init__(**kwargs)
        self.dissipation = dissipation

    def evaluate(self, z: Tensor, sigma: Tensor):
        state = super().evaluate(z, sigma)
        p = self.theory33_parameters
        chemical_force = (
            state.carrier_density - p.target_fraction * state.number_density
        ) / (
            p.chemical_susceptibility
            * state.number_density.clamp_min(1.0e-12)
        )
        drag_force = (
            state.carrier_rapidity - state.baryon_rapidity
        ) / p.relaxation_time
        force = torch.stack([chemical_force, drag_force], dim=-1)
        potential = self.dissipation(force)
        response = torch.autograd.grad(
            potential.sum(), force, create_graph=True
        )[0]
        state.residual = -response.sum(dim=-1)
        return state


class ConvexDriftResidual(nn.Module):
    """One-dimensional convex neural Bregman expansion in relative drift."""

    def __init__(self, width: int = 10, sharpness: float = 5.0) -> None:
        super().__init__()
        self.register_buffer("knots", torch.linspace(0.0, 1.0, width))
        self.register_buffer("sharpness", torch.tensor(sharpness))
        self.raw_quadratic = nn.Parameter(torch.tensor(0.541324854612918))
        self.raw_weights = nn.Parameter(torch.full((width,), -6.0))

    def forward(self, relative_drift: Tensor) -> Tensor:
        y = relative_drift[:, None]
        origin = torch.zeros_like(y)
        shifted = self.sharpness * (y - self.knots[None, :])
        shifted_origin = self.sharpness * (
            origin - self.knots[None, :]
        )
        value = F.softplus(shifted)
        value_origin = F.softplus(shifted_origin)
        derivative_origin = torch.sigmoid(shifted_origin) * self.sharpness
        bregman = value - value_origin - derivative_origin * y
        quadratic = (
            0.5 * F.softplus(self.raw_quadratic) * relative_drift.square()
        )
        return quadratic + torch.einsum(
            "bi,i->b", bregman, F.softplus(self.raw_weights)
        )


class PartiallyConvexMaster(Theory33MasterFunction):
    """Analytic M1 plus a smooth convex residual in relative drift."""

    def __init__(
        self,
        parameters: Theory33Parameters,
        drift_network: ConvexDriftResidual,
        *,
        amplitude: float = 1.0,
        drift_scale: float = 0.02,
        energy_scale: float = 1.0e-8,
    ) -> None:
        super().__init__(parameters, learn_residual=False)
        self.drift_network = drift_network
        self.register_buffer("amplitude", torch.tensor(amplitude))
        self.register_buffer("drift_scale", torch.tensor(drift_scale))
        self.register_buffer("energy_scale", torch.tensor(energy_scale))

    def relative_drift(self, features: Tensor) -> Tensor:
        n2, d2, cross, _entropy = features.unbind(dim=-1)
        product = torch.sqrt((n2 * d2).clamp_min(1.0e-24))
        return (cross / product - 1.0).clamp_min(0.0)

    def residual_energy(self, features: Tensor) -> Tensor:
        y = self.relative_drift(features) / self.drift_scale
        return self.energy_scale * self.drift_network(y)

    def forward(self, features: Tensor) -> Tensor:
        return self.base_lambda(features) - self.amplitude * self.residual_energy(
            features
        )


class TwoPhaseMaster(PartiallyConvexMaster):
    """Continuous potential with an explicit derivative jump at a phase edge."""

    def __init__(
        self,
        parameters: Theory33Parameters,
        drift_network: ConvexDriftResidual,
        *,
        phase_threshold: float,
        amplitude: float,
        drift_scale: float = 0.02,
        energy_scale: float = 1.0e-8,
    ) -> None:
        super().__init__(
            parameters,
            drift_network,
            amplitude=amplitude,
            drift_scale=drift_scale,
            energy_scale=energy_scale,
        )
        self.register_buffer(
            "phase_threshold", torch.tensor(phase_threshold)
        )

    def forward(self, features: Tensor) -> Tensor:
        base = self.base_lambda(features)
        drift = self.relative_drift(features)
        y = drift / self.drift_scale
        threshold_y = (
            self.phase_threshold / self.drift_scale
        ).expand_as(y)
        phase_residual = self.energy_scale * (
            self.drift_network(y)
            - self.drift_network(threshold_y)
        )
        phase_two = (drift >= self.phase_threshold).detach()
        return base - self.amplitude * torch.where(
            phase_two, phase_residual, torch.zeros_like(phase_residual)
        )


@dataclass
class ExperimentResult:
    name: str
    passed: bool
    metrics: dict[str, Any]

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


def compact_model_audit(
    model: Theory33HybridTesseract,
    *,
    basin_points: int = 129,
    characteristic_points: int = 9,
) -> dict[str, Any]:
    model.eval()
    basin = validate_broad_basin(
        model,
        steps=128,
        target=DEFAULT_TARGET,
        points=basin_points,
        characteristic_points=characteristic_points,
    )
    global_safety = validate_global_safety(
        model,
        steps=32,
        target=DEFAULT_TARGET,
        exponent_points=9,
    )
    passed = (
        bool(basin["kkt_valid"])
        and bool(basin["physical_valid"])
        and bool(basin["characteristic_valid"])
        and float(basin["max_abs_state"]) < 1.051
        and float(basin["converged_fraction"]) >= 0.99
        and bool(global_safety["finite"])
        and bool(global_safety["kkt_valid"])
        and bool(global_safety["physical_valid"])
        and float(global_safety["maximum_outer_gradient"]) == 0.0
    )
    return {
        "passed": passed,
        "basin": basin,
        "global_safety": global_safety,
    }


def experiment_neural_kappa(
    *,
    epochs: int = 800,
    samples_per_branch: int = 1024,
) -> ExperimentResult:
    """Distill the Chebyshev controller into a certified monotone network."""
    torch.manual_seed(3301)
    teacher = BroadBasinKappaController()
    controller = CertifiedNeuralKappaController()
    base_kappa = torch.tensor(-0.6352141942408)
    intervals = (
        controller.negative_interval,
        controller.positive_interval,
    )
    z = torch.cat(
        [
            torch.linspace(lower, upper, samples_per_branch)
            for lower, upper in intervals
        ]
    )
    with torch.no_grad():
        target = teacher(z, base_kappa) - base_kappa
        negative_count = samples_per_branch
        controller.negative.anchor.copy_(target[0])
        controller.positive.anchor.copy_(target[negative_count])

    optimizer = torch.optim.Adam(controller.parameters(), lr=8.0e-3)
    initial_prediction = controller.residual(z)
    initial_rmse = _rmse(initial_prediction, target)
    for _ in range(epochs):
        prediction = controller.residual(z)
        value_loss = (prediction - target).square().mean()
        endpoint_loss = (
            prediction[[0, samples_per_branch - 1, samples_per_branch, -1]]
            - target[[0, samples_per_branch - 1, samples_per_branch, -1]]
        ).square().mean()
        loss = value_loss + 4.0 * endpoint_loss
        optimizer.zero_grad(set_to_none=True)
        loss.backward()
        optimizer.step()

    prediction = controller.residual(z)
    final_rmse = _rmse(prediction, target)
    maximum_error = _float((prediction - target).abs().max())

    derivative_metrics: dict[str, float] = {}
    monotone = True
    for name, branch in (
        ("negative", controller.negative),
        ("positive", controller.positive),
    ):
        coordinate = torch.linspace(-1.0, 1.0, 513).requires_grad_(True)
        value = branch(coordinate)
        derivative = torch.autograd.grad(value.sum(), coordinate)[0]
        maximum_positive = _float(derivative.max())
        maximum_absolute = _float(derivative.abs().max())
        bound = _float(branch.slope_bound)
        monotone &= maximum_positive <= 1.0e-12
        monotone &= maximum_absolute <= bound + 1.0e-12
        derivative_metrics[f"{name}_maximum_positive_slope"] = (
            maximum_positive
        )
        derivative_metrics[f"{name}_maximum_absolute_slope"] = (
            maximum_absolute
        )
        derivative_metrics[f"{name}_certified_slope_bound"] = bound

    model = Theory33HybridTesseract(
        learn_dynamics=False, boundary_certificates=False
    )
    model.kappa_controller = controller
    audit = compact_model_audit(model)
    passed = bool(audit["passed"]) and monotone and maximum_error < 2.0e-3
    return ExperimentResult(
        name="certified_neural_kappa",
        passed=passed,
        metrics={
            "epochs": epochs,
            "samples_per_branch": samples_per_branch,
            "initial_rmse": initial_rmse,
            "final_rmse": final_rmse,
            "maximum_teacher_error": maximum_error,
            "monotone": monotone,
            **derivative_metrics,
            "audit": audit,
        },
    )


def _loss_and_derivative(
    model: Theory33HybridTesseract, z: Tensor
) -> tuple[Tensor, Tensor]:
    probe = z.detach().clone().requires_grad_(True)
    mapped, _diagnostics = model.step(probe)
    loss = 0.5 * (mapped - DEFAULT_TARGET).square()
    derivative = torch.autograd.grad(loss.sum(), probe)[0]
    return loss.detach(), derivative.detach()


def _discover_switch_boundaries(
    model: Theory33HybridTesseract,
    *,
    points: int = 1025,
    maximum_extra: int = 4,
) -> list[tuple[str, float]]:
    z = torch.linspace(-1.0, 1.0, points).requires_grad_(True)
    _mapped, diagnostics = model.step(z)
    active = diagnostics.active_mask
    classifier = diagnostics.classifier_mask
    found: list[tuple[str, float]] = []
    for label, values in (("kkt", active), ("classifier", classifier)):
        changed = torch.nonzero(values[1:] != values[:-1]).flatten()
        for index in changed[:maximum_extra]:
            boundary = _float(0.5 * (z[index] + z[index + 1]))
            if all(abs(boundary - item[1]) > 2.0e-3 for item in found):
                found.append((label, boundary))
    return found[:maximum_extra]


def experiment_nonsmooth_vjp() -> ExperimentResult:
    """Compare branchwise and jump-aware gradients of smoothed objectives."""
    model = Theory33HybridTesseract(
        learn_dynamics=False, boundary_certificates=False
    )
    boundaries: list[tuple[str, float]] = [
        ("outer", -1.0),
        ("parity", -2.0 / 3.0 - 0.05),
        ("parity", 2.0 / 3.0 - 0.05),
        ("outer", 1.0),
    ]
    boundaries.extend(_discover_switch_boundaries(model))
    delta = 2.0e-3
    side_epsilon = 1.0e-7
    records: list[dict[str, Any]] = []

    for kind, boundary in boundaries:
        samples = boundary + torch.linspace(-delta, delta, 1001)
        loss, derivative = _loss_and_derivative(model, samples)
        branchwise = _float(derivative.mean())
        endpoint_loss, _ = _loss_and_derivative(
            model, torch.tensor([boundary - delta, boundary + delta])
        )
        smoothed_reference = _float(
            (endpoint_loss[1] - endpoint_loss[0]) / (2.0 * delta)
        )
        side_loss, side_derivative = _loss_and_derivative(
            model,
            torch.tensor(
                [boundary - side_epsilon, boundary + side_epsilon]
            ),
        )
        jump = _float(side_loss[1] - side_loss[0])
        jump_aware = branchwise + jump / (2.0 * delta)
        left_derivative = _float(side_derivative[0])
        right_derivative = _float(side_derivative[1])
        continuous = abs(jump) < 1.0e-5
        records.append(
            {
                "kind": kind,
                "boundary": boundary,
                "continuous": continuous,
                "loss_jump": jump,
                "left_derivative": left_derivative,
                "right_derivative": right_derivative,
                "conservative_midpoint": 0.5
                * (left_derivative + right_derivative),
                "branchwise_smoothed_vjp": branchwise,
                "jump_aware_smoothed_vjp": jump_aware,
                "smoothed_reference": smoothed_reference,
                "branchwise_error": abs(branchwise - smoothed_reference),
                "jump_aware_error": abs(jump_aware - smoothed_reference),
            }
        )

    discontinuous = [item for item in records if not item["continuous"]]
    continuous = [item for item in records if item["continuous"]]
    branch_error = sum(item["branchwise_error"] for item in records) / len(
        records
    )
    jump_error = sum(item["jump_aware_error"] for item in records) / len(
        records
    )
    jump_improved = all(
        item["jump_aware_error"] < item["branchwise_error"]
        for item in discontinuous
    )
    continuous_well_behaved = all(
        item["branchwise_error"] < 5.0e-2 for item in continuous
    )
    passed = (
        bool(discontinuous)
        and bool(continuous)
        and jump_improved
        and continuous_well_behaved
        and jump_error < branch_error
    )
    return ExperimentResult(
        name="nonsmooth_boundary_vjp",
        passed=passed,
        metrics={
            "smoothing_half_width": delta,
            "boundary_count": len(records),
            "continuous_count": len(continuous),
            "discontinuous_count": len(discontinuous),
            "mean_branchwise_error": branch_error,
            "mean_jump_aware_error": jump_error,
            "jump_improved_every_discontinuity": jump_improved,
            "records": records,
        },
    )


def _teacher_dissipation(force: Tensor) -> Tensor:
    relative = force[:, 0] - force[:, 1]
    return 0.5 * force.square().sum(dim=-1) + 5.0 * relative.pow(4)


def experiment_convex_dissipation(
    *,
    epochs: int = 700,
    samples: int = 2048,
) -> ExperimentResult:
    """Learn a nonlinear convex dissipation potential and use its gradient."""
    torch.manual_seed(3302)
    potential = ConvexDissipationPotential()
    chemical = 0.004 * torch.rand(samples) - 0.002
    drag = 0.4 * torch.rand(samples) - 0.2
    force = torch.stack([chemical, drag], dim=-1).requires_grad_(True)
    teacher = _teacher_dissipation(force)
    teacher_response = torch.autograd.grad(
        teacher.sum(), force, create_graph=False
    )[0].detach()
    optimizer = torch.optim.Adam(potential.parameters(), lr=5.0e-3)
    initial_response = torch.autograd.grad(
        potential(force).sum(), force, create_graph=True
    )[0]
    initial_rmse = _rmse(initial_response, teacher_response)

    for _ in range(epochs):
        prediction = potential(force)
        response = torch.autograd.grad(
            prediction.sum(), force, create_graph=True
        )[0]
        response_loss = (response - teacher_response).square().mean()
        value_loss = (prediction - teacher.detach()).square().mean()
        loss = response_loss + 0.2 * value_loss
        optimizer.zero_grad(set_to_none=True)
        loss.backward()
        optimizer.step()

    prediction = potential(force)
    response = torch.autograd.grad(
        prediction.sum(), force, create_graph=True
    )[0]
    final_response_rmse = _rmse(response, teacher_response)
    final_value_rmse = _rmse(prediction, teacher)
    minimum_potential = _float(prediction.min())

    hessian_minimum = math.inf
    for point in torch.stack(
        [
            torch.zeros(2),
            torch.tensor([-0.002, -0.2]),
            torch.tensor([0.002, 0.2]),
            torch.tensor([0.0, -0.1]),
            torch.tensor([0.0, 0.1]),
        ]
    ):
        hessian = torch.autograd.functional.hessian(
            lambda value: potential(value[None, :])[0], point
        )
        hessian_minimum = min(
            hessian_minimum, _float(torch.linalg.eigvalsh(hessian)[0])
        )

    model = NeuralDissipationTheory33(
        potential,
        learn_dynamics=False,
        boundary_certificates=False,
    )
    audit = compact_model_audit(model)
    passed = (
        bool(audit["passed"])
        and minimum_potential >= -1.0e-12
        and hessian_minimum > 0.0
        and final_response_rmse < initial_rmse
        and final_response_rmse < 3.0e-2
    )
    return ExperimentResult(
        name="convex_neural_dissipation",
        passed=passed,
        metrics={
            "epochs": epochs,
            "samples": samples,
            "initial_response_rmse": initial_rmse,
            "final_response_rmse": final_response_rmse,
            "final_value_rmse": final_value_rmse,
            "minimum_sampled_potential": minimum_potential,
            "minimum_sampled_hessian_eigenvalue": hessian_minimum,
            "audit": audit,
        },
    )


def train_convex_drift_network(
    *,
    epochs: int = 700,
    samples: int = 1025,
) -> tuple[ConvexDriftResidual, dict[str, float]]:
    """Fit a convex neural residual to a quadratic drift-energy teacher."""
    torch.manual_seed(3303)
    network = ConvexDriftResidual()
    y = torch.linspace(0.0, 1.0, samples).requires_grad_(True)
    target = 0.5 * y.detach().square()
    target_derivative = y.detach()
    optimizer = torch.optim.Adam(network.parameters(), lr=8.0e-3)
    initial = network(y)
    initial_rmse = _rmse(initial, target)
    for _ in range(epochs):
        prediction = network(y)
        derivative = torch.autograd.grad(
            prediction.sum(), y, create_graph=True
        )[0]
        value_loss = (prediction - target).square().mean()
        derivative_loss = (
            derivative - target_derivative
        ).square().mean()
        loss = value_loss + 0.5 * derivative_loss
        optimizer.zero_grad(set_to_none=True)
        loss.backward()
        optimizer.step()
    prediction = network(y)
    derivative = torch.autograd.grad(prediction.sum(), y)[0]
    second_difference = (
        prediction[2:] - 2.0 * prediction[1:-1] + prediction[:-2]
    )
    return network, {
        "initial_value_rmse": initial_rmse,
        "final_value_rmse": _rmse(prediction, target),
        "final_derivative_rmse": _rmse(
            derivative, target_derivative
        ),
        "maximum_fitted_value": _float(prediction.max()),
        "minimum_discrete_second_difference": _float(
            second_difference.min()
        ),
        "origin_value": _float(prediction[0]),
        "origin_derivative": _float(derivative[0]),
    }


def _model_with_master(
    master: Theory33MasterFunction,
) -> Theory33HybridTesseract:
    model = Theory33HybridTesseract(
        learn_dynamics=False, boundary_certificates=False
    )
    model.master = master
    return model


def experiment_partially_convex_master(
    *,
    epochs: int = 700,
) -> tuple[ExperimentResult, ConvexDriftResidual, float]:
    """Fit and homotopy-qualify a convex relative-drift master residual."""
    network, fit_metrics = train_convex_drift_network(epochs=epochs)
    parameters = Theory33Parameters()
    attempted: list[dict[str, Any]] = []
    selected_amplitude = 0.0
    selected_audit: dict[str, Any] | None = None
    for amplitude in (1.0, 0.5, 0.25, 0.1, 0.05, 0.02, 0.01):
        master = PartiallyConvexMaster(
            parameters, network, amplitude=amplitude
        )
        model = _model_with_master(master)
        audit = compact_model_audit(
            model, basin_points=97, characteristic_points=9
        )
        attempted.append(
            {
                "amplitude": amplitude,
                "passed": bool(audit["passed"]),
                "max_characteristic_speed": audit["basin"][
                    "max_characteristic_speed"
                ],
                "min_physical_margin": audit["basin"][
                    "min_physical_margin"
                ],
            }
        )
        if bool(audit["passed"]):
            selected_amplitude = amplitude
            selected_audit = audit
            break

    passed = (
        selected_audit is not None
        and fit_metrics["final_value_rmse"] < 2.0e-2
        and fit_metrics["minimum_discrete_second_difference"] >= -1.0e-12
        and abs(fit_metrics["origin_value"]) < 1.0e-12
        and abs(fit_metrics["origin_derivative"]) < 1.0e-10
    )
    return (
        ExperimentResult(
            name="partially_convex_carter_master",
            passed=passed,
            metrics={
                "epochs": epochs,
                "fit": fit_metrics,
                "energy_scale": 1.0e-8,
                "maximum_scaled_residual_energy_on_fit_domain": (
                    1.0e-8 * fit_metrics["maximum_fitted_value"]
                ),
                "drift_scale": 0.02,
                "selected_amplitude": selected_amplitude,
                "homotopy_attempts": attempted,
                "audit": selected_audit,
            },
        ),
        network,
        selected_amplitude,
    )


def _fit_phase_threshold(
    network: ConvexDriftResidual,
    amplitude: float,
    *,
    true_threshold: float = 0.006,
) -> tuple[float, float]:
    drift_scale = 0.02
    energy_scale = 1.0e-8
    drift = torch.linspace(0.0, 0.02, 2001)
    y = drift / drift_scale
    true_y = torch.full_like(y, true_threshold / drift_scale)
    base_response = energy_scale * (
        network(y) - network(true_y)
    )
    target = amplitude * torch.where(
        drift >= true_threshold,
        base_response,
        torch.zeros_like(base_response),
    )
    candidates = torch.linspace(0.003, 0.009, 121)
    losses = []
    for threshold in candidates:
        threshold_y = torch.full_like(y, threshold / drift_scale)
        response = amplitude * torch.where(
            drift >= threshold,
            energy_scale * (network(y) - network(threshold_y)),
            torch.zeros_like(y),
        )
        losses.append((response - target).square().mean())
    loss_tensor = torch.stack(losses)
    index = int(torch.argmin(loss_tensor))
    return _float(candidates[index]), _float(loss_tensor[index])


def _phase_jump_metrics(master: TwoPhaseMaster) -> dict[str, float]:
    density = torch.tensor(0.12)
    carrier = torch.tensor(0.006)
    entropy = torch.tensor(1.0)
    epsilon = 1.0e-8
    features = []
    for drift in (
        _float(master.phase_threshold) - epsilon,
        _float(master.phase_threshold) + epsilon,
    ):
        features.append(
            torch.stack(
                [
                    density.square(),
                    carrier.square(),
                    density * carrier * (1.0 + drift),
                    entropy,
                ]
            )
        )
    inputs = torch.stack(features).requires_grad_(True)
    values = master(inputs)
    gradients = torch.autograd.grad(values.sum(), inputs)[0]
    return {
        "potential_jump": _float((values[1] - values[0]).abs()),
        "constitutive_gradient_jump_norm": _float(
            torch.linalg.vector_norm(gradients[1] - gradients[0])
        ),
    }


def experiment_two_phase_master(
    drift_network: ConvexDriftResidual,
    amplitude: float,
) -> ExperimentResult:
    """Fit a hard phase edge between two individually qualified potentials."""
    if amplitude <= 0.0:
        return ExperimentResult(
            name="explicit_two_phase_master",
            passed=False,
            metrics={"reason": "no qualified residual amplitude"},
        )
    threshold, threshold_loss = _fit_phase_threshold(
        drift_network, amplitude
    )
    master = TwoPhaseMaster(
        Theory33Parameters(),
        drift_network,
        phase_threshold=threshold,
        amplitude=amplitude,
    )
    model = _model_with_master(master)
    audit = compact_model_audit(
        model, basin_points=97, characteristic_points=13
    )

    z = torch.linspace(-1.0, 1.05, 513).requires_grad_(True)
    phase_counts = [0, 0]
    for sigma_value in (-1.0, 1.0):
        sigma = torch.full_like(z, sigma_value)
        state = model.evaluate(z, sigma)
        phase_two = state.relative_lorentz_factor - 1.0 >= threshold
        phase_counts[0] += int((~phase_two).sum())
        phase_counts[1] += int(phase_two.sum())
    jump = _phase_jump_metrics(master)
    passed = (
        bool(audit["passed"])
        and threshold_loss < 1.0e-20
        and phase_counts[0] > 0
        and phase_counts[1] > 0
        and jump["potential_jump"] < 1.0e-8
        and jump["constitutive_gradient_jump_norm"] > 0.0
    )
    return ExperimentResult(
        name="explicit_two_phase_master",
        passed=passed,
        metrics={
            "fitted_phase_threshold": threshold,
            "threshold_fit_mse": threshold_loss,
            "phase_one_samples": phase_counts[0],
            "phase_two_samples": phase_counts[1],
            **jump,
            "audit": audit,
        },
    )


def run_all_experiments(
    *,
    quick: bool = False,
) -> list[ExperimentResult]:
    """Run the five experiments in dependency order."""
    kappa = experiment_neural_kappa(
        epochs=450 if quick else 800,
        samples_per_branch=257 if quick else 1024,
    )
    nonsmooth = experiment_nonsmooth_vjp()
    dissipation = experiment_convex_dissipation(
        epochs=300 if quick else 700,
        samples=512 if quick else 2048,
    )
    master, drift_network, amplitude = experiment_partially_convex_master(
        epochs=300 if quick else 700
    )
    two_phase = experiment_two_phase_master(drift_network, amplitude)
    return [kappa, nonsmooth, dissipation, master, two_phase]
